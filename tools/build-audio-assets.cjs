'use strict';

// Embed the original compressed files so direct file-open play needs no fetch.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const directory = path.resolve(__dirname, '../assets/audio');
const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'manifest.json'), 'utf8'));
const samples = {};
for (const sample of manifest.samples) {
  if (!/^[a-z][a-z0-9-]*$/.test(sample.id) || Object.hasOwn(samples, sample.id) ||
      !/^[a-z0-9-]+\.mp3$/.test(sample.file)) throw new Error('Invalid or duplicate audio sample entry.');
  const bytes = fs.readFileSync(path.join(directory, sample.file));
  if (bytes.length < 100 || bytes.length > 1024 * 1024) throw new Error('Unexpected audio sample size: ' + sample.file);
  const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
  if (sample.sha256 && sample.sha256 !== sha256) throw new Error('Audio source digest changed: ' + sample.file);
  samples[sample.id] = { data: bytes.toString('base64'), loop: sample.loop === true, gain: sample.gain ?? 1,
    ...(sample.baseFrequency ? { baseFrequency: sample.baseFrequency } : {}), sha256 };
}
const source = '// Generated by node tools/build-audio-assets.cjs. Edit the manifest/source MP3s, then rebuild.\n' +
  '// Embedded compressed audio preserves offline and file-open playback.\n' +
  '(function (root) {\n  "use strict";\n  const samples = ' + JSON.stringify(samples) + ';\n' +
  '  Object.values(samples).forEach(Object.freeze); Object.freeze(samples);\n' +
  '  if (typeof module !== "undefined" && module.exports) module.exports = samples;\n' +
  '  root.MayhemAudioSamples = samples;\n})(typeof globalThis !== "undefined" ? globalThis : this);\n';
const output = path.join(directory, 'samples.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== source) {
    throw new Error('Embedded audio is stale. Run npm run audio-assets.');
  }
  console.log(Object.keys(samples).length + ' embedded audio samples match their source files.');
} else {
  fs.writeFileSync(output, source);
  console.log('Bundled ' + Object.keys(samples).length + ' audio samples (' + Buffer.byteLength(source) + ' bytes).');
}
